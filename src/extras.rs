/// Outil construit seulement à sa première ouverture : le démarrage ne paie que pour ce qu'on utilise.
struct Paresseux {
    nom: &'static str,
    cat: Cat,
    faire: Option<Box<dyn FnOnce() -> Box<dyn Outil>>>,
    o: Option<Box<dyn Outil>>,
}

fn paresseux(nom: &'static str, cat: Cat, faire: impl FnOnce() -> Box<dyn Outil> + 'static) -> Box<dyn Outil> {
    crate::moi::A_LA_DEMANDE.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    Box::new(Paresseux { nom, cat, faire: Some(Box::new(faire)), o: None })
}

impl Outil for Paresseux {
    fn nom(&self) -> &'static str {
        self.nom
    }
    fn cat(&self) -> Cat {
        self.cat
    }
    fn ui(&mut self, ui: &mut eframe::egui::Ui) {
        if self.o.is_none() {
            if let Some(f) = self.faire.take() {
                self.o = Some(f());
                crate::moi::CHARGES.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
            }
        }
        if let Some(o) = &mut self.o {
            o.ui(ui);
        }
    }
    fn tic(&mut self, ctx: &eframe::egui::Context) {
        if let Some(o) = &mut self.o {
            o.tic(ctx);
        }
    }
    fn resume(&self) -> Option<String> {
        self.o.as_ref().and_then(|o| o.resume())
    }
}
